def kind(s):
    if s['total'] == 0: return None
    m, mh, nb, t = s['margin'], s['marginHits'], s['snapshotNotBaseline'], s['total']
    if m == 0: return None
    if nb == 0 and mh <= 3: return 'whole'
    if nb <= 0.1 * t and mh <= max(3, 0.1 * m): return 'rewrite'
    if m - mh >= 15: return 'fragment'
    return None

